"""Typography & Text Tool Options for Secondary Toolbar."""

from PySide6 import QtCore, QtGui, QtWidgets
from ui.core.icons import get_icon

def build_text_panels(toolbar):
    # Horizontal
    p_h = QtWidgets.QWidget()
    l_h = QtWidgets.QHBoxLayout(p_h)
    l_h.setContentsMargins(0, 0, 0, 0)
    l_h.setSpacing(8)
    l_h.setAlignment(QtCore.Qt.AlignVCenter)

    lbl_i = QtWidgets.QLabel()
    lbl_i.setFixedSize(16, 16)
    lbl_i.setPixmap(get_icon("text").pixmap(14, 14))
    l_h.addWidget(lbl_i)

    toolbar.cbo_text_font_h = QtWidgets.QFontComboBox()
    toolbar.cbo_text_font_h.setCurrentFont(QtGui.QFont("Segoe UI"))
    toolbar.cbo_text_font_h.setFixedHeight(24)
    toolbar.cbo_text_font_h.setFixedWidth(130)
    toolbar.cbo_text_font_h.currentFontChanged.connect(lambda f: toolbar._on_text_font_changed(f, "h"))
    l_h.addWidget(toolbar.cbo_text_font_h)

    l_h.addWidget(QtWidgets.QLabel("Tam:"))
    toolbar.spin_text_size_h = QtWidgets.QSpinBox()
    toolbar.spin_text_size_h.setRange(8, 288)
    toolbar.spin_text_size_h.setValue(36)
    toolbar.spin_text_size_h.setSuffix(" pt")
    toolbar.spin_text_size_h.setFixedHeight(24)
    toolbar.spin_text_size_h.setFixedWidth(75)
    toolbar.spin_text_size_h.valueChanged.connect(lambda v: toolbar._on_text_size_changed(v, "h"))
    l_h.addWidget(toolbar.spin_text_size_h)

    toolbar.btn_text_bold_h = QtWidgets.QToolButton()
    toolbar.btn_text_bold_h.setText("B")
    toolbar.btn_text_bold_h.setStyleSheet("font-weight: bold;")
    toolbar.btn_text_bold_h.setCheckable(True)
    toolbar.btn_text_bold_h.setFixedSize(24, 24)
    toolbar.btn_text_bold_h.toggled.connect(lambda v: toolbar._on_text_bold_toggled(v, "h"))
    l_h.addWidget(toolbar.btn_text_bold_h)

    toolbar.btn_text_italic_h = QtWidgets.QToolButton()
    toolbar.btn_text_italic_h.setText("I")
    toolbar.btn_text_italic_h.setStyleSheet("font-style: italic; font-weight: bold;")
    toolbar.btn_text_italic_h.setCheckable(True)
    toolbar.btn_text_italic_h.setFixedSize(24, 24)
    toolbar.btn_text_italic_h.toggled.connect(lambda v: toolbar._on_text_italic_toggled(v, "h"))
    l_h.addWidget(toolbar.btn_text_italic_h)

    toolbar.btn_text_underline_h = QtWidgets.QToolButton()
    toolbar.btn_text_underline_h.setText("U")
    toolbar.btn_text_underline_h.setStyleSheet("text-decoration: underline; font-weight: bold;")
    toolbar.btn_text_underline_h.setCheckable(True)
    toolbar.btn_text_underline_h.setFixedSize(24, 24)
    toolbar.btn_text_underline_h.toggled.connect(lambda v: toolbar._on_text_underline_toggled(v, "h"))
    l_h.addWidget(toolbar.btn_text_underline_h)

    toolbar.btn_text_align_l_h = QtWidgets.QToolButton()
    toolbar.btn_text_align_l_h.setText("Esq")
    toolbar.btn_text_align_l_h.setCheckable(True)
    toolbar.btn_text_align_l_h.setChecked(True)
    toolbar.btn_text_align_l_h.setFixedHeight(24)
    toolbar.btn_text_align_l_h.clicked.connect(lambda: toolbar._on_text_align_changed("left", "h"))
    l_h.addWidget(toolbar.btn_text_align_l_h)

    toolbar.btn_text_align_c_h = QtWidgets.QToolButton()
    toolbar.btn_text_align_c_h.setText("Cen")
    toolbar.btn_text_align_c_h.setCheckable(True)
    toolbar.btn_text_align_c_h.setFixedHeight(24)
    toolbar.btn_text_align_c_h.clicked.connect(lambda: toolbar._on_text_align_changed("center", "h"))
    l_h.addWidget(toolbar.btn_text_align_c_h)

    toolbar.btn_text_align_r_h = QtWidgets.QToolButton()
    toolbar.btn_text_align_r_h.setText("Dir")
    toolbar.btn_text_align_r_h.setCheckable(True)
    toolbar.btn_text_align_r_h.setFixedHeight(24)
    toolbar.btn_text_align_r_h.clicked.connect(lambda: toolbar._on_text_align_changed("right", "h"))
    l_h.addWidget(toolbar.btn_text_align_r_h)

    l_h.addWidget(QtWidgets.QLabel("Cor:"))
    toolbar.btn_text_color_h = QtWidgets.QPushButton()
    toolbar.btn_text_color_h.setFixedSize(20, 20)
    toolbar.btn_text_color_h.setStyleSheet(f"background: {toolbar._text_color.name()}; border-radius: 4px; border: 1px solid rgba(255,255,255,0.4);")
    toolbar.btn_text_color_h.clicked.connect(toolbar._pick_text_color)
    l_h.addWidget(toolbar.btn_text_color_h)

    toolbar.btn_text_commit_h = QtWidgets.QPushButton("Inserir")
    toolbar.btn_text_commit_h.setFixedHeight(24)
    toolbar.btn_text_commit_h.clicked.connect(toolbar._on_commit_text_clicked)
    l_h.addWidget(toolbar.btn_text_commit_h)

    toolbar.btn_text_cancel_h = QtWidgets.QPushButton("✕")
    toolbar.btn_text_cancel_h.setFixedSize(24, 24)
    toolbar.btn_text_cancel_h.clicked.connect(toolbar._on_cancel_text_clicked)
    l_h.addWidget(toolbar.btn_text_cancel_h)

    # Vertical
    p_v = QtWidgets.QWidget()
    l_v = QtWidgets.QVBoxLayout(p_v)
    l_v.setContentsMargins(0, 0, 0, 0)
    l_v.setSpacing(6)

    h = QtWidgets.QHBoxLayout()
    lbl_iv = QtWidgets.QLabel()
    lbl_iv.setFixedSize(16, 16)
    lbl_iv.setPixmap(get_icon("text").pixmap(14, 14))
    h.addWidget(lbl_iv)
    lbl_t = QtWidgets.QLabel("TEXTO TIPOGRÁFICO")
    lbl_t.setStyleSheet("font-size: 10px; font-weight: bold; color: #a1a1aa;")
    h.addWidget(lbl_t)
    h.addStretch()
    l_v.addLayout(h)

    toolbar.cbo_text_font_v = QtWidgets.QFontComboBox()
    toolbar.cbo_text_font_v.setCurrentFont(QtGui.QFont("Segoe UI"))
    toolbar.cbo_text_font_v.setFixedHeight(24)
    toolbar.cbo_text_font_v.currentFontChanged.connect(lambda f: toolbar._on_text_font_changed(f, "v"))
    l_v.addWidget(toolbar.cbo_text_font_v)

    r_sz = QtWidgets.QHBoxLayout()
    r_sz.addWidget(QtWidgets.QLabel("Tam:"))
    r_sz.addStretch()
    toolbar.spin_text_size_v = QtWidgets.QSpinBox()
    toolbar.spin_text_size_v.setRange(8, 288)
    toolbar.spin_text_size_v.setValue(36)
    toolbar.spin_text_size_v.setSuffix(" pt")
    toolbar.spin_text_size_v.setFixedHeight(24)
    toolbar.spin_text_size_v.setFixedWidth(75)
    toolbar.spin_text_size_v.valueChanged.connect(lambda v: toolbar._on_text_size_changed(v, "v"))
    r_sz.addWidget(toolbar.spin_text_size_v)
    l_v.addLayout(r_sz)

    r_st = QtWidgets.QHBoxLayout()
    r_st.addWidget(QtWidgets.QLabel("Estilo:"))
    r_st.addStretch()
    toolbar.btn_text_bold_v = QtWidgets.QToolButton()
    toolbar.btn_text_bold_v.setText("B")
    toolbar.btn_text_bold_v.setStyleSheet("font-weight: bold;")
    toolbar.btn_text_bold_v.setCheckable(True)
    toolbar.btn_text_bold_v.setFixedSize(28, 24)
    toolbar.btn_text_bold_v.toggled.connect(lambda v: toolbar._on_text_bold_toggled(v, "v"))
    r_st.addWidget(toolbar.btn_text_bold_v)

    toolbar.btn_text_italic_v = QtWidgets.QToolButton()
    toolbar.btn_text_italic_v.setText("I")
    toolbar.btn_text_italic_v.setStyleSheet("font-style: italic; font-weight: bold;")
    toolbar.btn_text_italic_v.setCheckable(True)
    toolbar.btn_text_italic_v.setFixedSize(28, 24)
    toolbar.btn_text_italic_v.toggled.connect(lambda v: toolbar._on_text_italic_toggled(v, "v"))
    r_st.addWidget(toolbar.btn_text_italic_v)

    toolbar.btn_text_underline_v = QtWidgets.QToolButton()
    toolbar.btn_text_underline_v.setText("U")
    toolbar.btn_text_underline_v.setStyleSheet("text-decoration: underline; font-weight: bold;")
    toolbar.btn_text_underline_v.setCheckable(True)
    toolbar.btn_text_underline_v.setFixedSize(28, 24)
    toolbar.btn_text_underline_v.toggled.connect(lambda v: toolbar._on_text_underline_toggled(v, "v"))
    r_st.addWidget(toolbar.btn_text_underline_v)
    l_v.addLayout(r_st)

    r_al = QtWidgets.QHBoxLayout()
    r_al.addWidget(QtWidgets.QLabel("Alinhar:"))
    r_al.addStretch()
    toolbar.btn_text_align_l_v = QtWidgets.QToolButton()
    toolbar.btn_text_align_l_v.setText("Esq")
    toolbar.btn_text_align_l_v.setCheckable(True)
    toolbar.btn_text_align_l_v.setChecked(True)
    toolbar.btn_text_align_l_v.setFixedHeight(24)
    toolbar.btn_text_align_l_v.clicked.connect(lambda: toolbar._on_text_align_changed("left", "v"))
    r_al.addWidget(toolbar.btn_text_align_l_v)

    toolbar.btn_text_align_c_v = QtWidgets.QToolButton()
    toolbar.btn_text_align_c_v.setText("Cen")
    toolbar.btn_text_align_c_v.setCheckable(True)
    toolbar.btn_text_align_c_v.setFixedHeight(24)
    toolbar.btn_text_align_c_v.clicked.connect(lambda: toolbar._on_text_align_changed("center", "v"))
    r_al.addWidget(toolbar.btn_text_align_c_v)

    toolbar.btn_text_align_r_v = QtWidgets.QToolButton()
    toolbar.btn_text_align_r_v.setText("Dir")
    toolbar.btn_text_align_r_v.setCheckable(True)
    toolbar.btn_text_align_r_v.setFixedHeight(24)
    toolbar.btn_text_align_r_v.clicked.connect(lambda: toolbar._on_text_align_changed("right", "v"))
    r_al.addWidget(toolbar.btn_text_align_r_v)
    l_v.addLayout(r_al)

    r_col = QtWidgets.QHBoxLayout()
    r_col.addWidget(QtWidgets.QLabel("Cor:"))
    r_col.addStretch()
    toolbar.btn_text_color_v = QtWidgets.QPushButton()
    toolbar.btn_text_color_v.setFixedSize(20, 20)
    toolbar.btn_text_color_v.setStyleSheet(f"background: {toolbar._text_color.name()}; border-radius: 4px; border: 1px solid rgba(255,255,255,0.4);")
    toolbar.btn_text_color_v.clicked.connect(toolbar._pick_text_color)
    r_col.addWidget(toolbar.btn_text_color_v)
    l_v.addLayout(r_col)

    r_act = QtWidgets.QHBoxLayout()
    toolbar.btn_text_cancel_v = QtWidgets.QPushButton("Cancelar")
    toolbar.btn_text_cancel_v.setFixedHeight(24)
    toolbar.btn_text_cancel_v.clicked.connect(toolbar._on_cancel_text_clicked)
    r_act.addWidget(toolbar.btn_text_cancel_v)

    toolbar.btn_text_commit_v = QtWidgets.QPushButton("Inserir Texto")
    toolbar.btn_text_commit_v.setFixedHeight(24)
    toolbar.btn_text_commit_v.clicked.connect(toolbar._on_commit_text_clicked)
    r_act.addWidget(toolbar.btn_text_commit_v)
    l_v.addLayout(r_act)

    toolbar.stacked_widget.addWidget(p_h)
    toolbar.stacked_widget.addWidget(p_v)
    toolbar._panels_h["text"] = p_h
    toolbar._panels_v["text"] = p_v
