"""Porta da janela principal: o que a casca usa do workspace e do canvas.

O workspace é do plugin de sistema WorkspaceCore; a casca (ui/boundary) não
importa plugin. Ela recebe o `WorkspaceContainer` pelo `setCentralWidget` e
fala com ele só pelo que está declarado aqui. O teste
`tests/test_main_window_collaborators.py` confere que o `WorkspaceContainer` e
o `RenderWidget` cumprem estes contratos.

Antes de 2026-09-24 a casca descobria o que o workspace tinha com `hasattr`
(22 no main_window.py) e chegava a chamar métodos privados dele
(`_sync_navigator_to_canvas`, `_load_custom_texture`, este último inexistente).
"""
from __future__ import annotations

from typing import Any, Callable, Protocol

from PySide6 import QtCore, QtGui


class ShellCanvas(Protocol):
    """O canvas visto pela casca (implementado por `RenderWidget`)."""

    strokeStarted: QtCore.SignalInstance
    strokeFinished: QtCore.SignalInstance
    rotation: float
    flip_x: bool
    flip_y: bool

    @property
    def is_busy(self) -> bool: ...
    def update(self) -> None: ...
    def publish_view(self, zoom_changed: bool = False, notify_camera: bool = True) -> None: ...
    def run_as_stroke(self, action: Callable[[], Any]) -> Any: ...
    def forward_key(self, event: QtGui.QKeyEvent, pressed: bool) -> bool: ...
    def select_all(self) -> None: ...
    def invert_selection(self) -> None: ...
    def clear_selection(self) -> None: ...
    def modify_selection(self, mode: str, radius_px: int) -> bool: ...
    def toggle_grid(self) -> bool: ...
    def toggle_rulers(self) -> bool: ...
    def apply_cursor_settings(self, settings: dict) -> None: ...


class ShellWorkspace(Protocol):
    """O workspace visto pela casca (implementado por `WorkspaceContainer`)."""

    canvas_widget: ShellCanvas
    zoomChanged: QtCore.SignalInstance
    statusMessage: QtCore.SignalInstance
    newDocumentRequested: QtCore.SignalInstance
    documentCloseRequested: QtCore.SignalInstance

    def undo(self) -> None: ...
    def redo(self) -> None: ...
    def reset_view(self) -> None: ...
    def zoom_in(self) -> None: ...
    def zoom_out(self) -> None: ...
    def refresh_document_state(self, doc: Any) -> None: ...
    def refresh_previews(self) -> None: ...
    def retranslate_ui(self) -> None: ...
    def toggle_panel_from_menu(self, panel_id: str, side: str) -> None: ...
    def collapse_all_sidebars(self) -> None: ...
    def expand_all_sidebars(self) -> None: ...
    def apply_dock_settings(self, cfg: dict) -> None: ...
    def dock_panels(self) -> dict: ...
    def apply_floating_toolbar_settings(self, cfg: dict) -> None: ...


# Nomes conferidos pelo teste de contrato (Protocol não é verificável em
# tempo de execução para atributos de instância).
